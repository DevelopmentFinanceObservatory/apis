"""The plural noun of each ISO 4217 code, lower case but for proper adjectives and names."""


def currency_noun(currency: str, *, label: str | None) -> str:
    """The noun the unit token names `currency` by: its `CURRENCY_NOUNS` entry, else the
    graph's ``label`` for the unit, else the ISO code."""
    return CURRENCY_NOUNS.get(currency) or label or currency
